//! Orchestration layer for the V3 Native build, validation, and query commands.

mod args;
mod benchmark;
mod build;
mod evidence;
mod finalize;
mod query;

use anyhow::Result;
use clap::Parser;
use gem_core::SearchParamsV3;
use gem_search::GraphBuildParamsV3;

use args::{Cli, Command};
use benchmark::cluster_benchmark;
use build::{build, repair_probe, validate};
use query::{determinism, exact_oracle, query};

pub fn run() -> Result<()> {
    let cli = Cli::parse();
    match cli.command {
        Command::Build {
            index_builder_commit,
            builder_kind,
            repair_policy,
            fine_centroids_npy,
            coarse_centroids_npy,
            fine_to_coarse_npy,
            code_dir,
            doclens_dir,
            output,
            checkpoint,
            report,
            progress_jsonl,
            posting_sizes_json,
            dimension,
            max_doc_tokens,
            m,
            m0,
            ef_construction,
            qemd_max_iterations,
            wave_size,
            build_threads,
            stop_after_cluster,
            resume,
        } => build(
            index_builder_commit,
            builder_kind,
            repair_policy,
            fine_centroids_npy,
            coarse_centroids_npy,
            fine_to_coarse_npy,
            code_dir,
            doclens_dir,
            output,
            checkpoint,
            report,
            progress_jsonl,
            posting_sizes_json,
            dimension,
            max_doc_tokens,
            GraphBuildParamsV3 {
                m,
                m0,
                ef_construction,
                qemd_max_iterations,
                wave_size,
            },
            build_threads,
            stop_after_cluster,
            resume,
        ),
        Command::Finalize {
            build_report,
            output,
            report,
        } => finalize::finalize(&build_report, &output, &report),
        Command::Validate { index, report } => validate(&index, &report),
        Command::RepairProbe {
            checkpoint,
            repair_policy,
            fine_centroids_npy,
            fine_to_coarse_npy,
            code_dir,
            doclens_dir,
            output,
            dimension,
            max_doc_tokens,
        } => repair_probe(
            &checkpoint,
            repair_policy,
            &fine_centroids_npy,
            &fine_to_coarse_npy,
            &code_dir,
            &doclens_dir,
            &output,
            dimension,
            max_doc_tokens,
        ),
        Command::Query {
            index,
            encoder_dir,
            code_dir,
            queries_npy,
            query_ids,
            output,
            query_tokens,
            k,
            rerank_k,
            cluster_top_t,
            ef_search,
            threads,
        } => query(
            &index,
            &encoder_dir,
            &code_dir,
            &queries_npy,
            &query_ids,
            &output,
            query_tokens,
            SearchParamsV3 {
                k,
                rerank_k,
                cluster_top_t,
                ef_search,
            },
            threads,
        ),
        Command::ExactOracle {
            index,
            encoder_dir,
            code_dir,
            queries_npy,
            query_ids,
            output,
            query_tokens,
            k,
            threads,
        } => exact_oracle(
            &index,
            &encoder_dir,
            &code_dir,
            &queries_npy,
            &query_ids,
            &output,
            query_tokens,
            k,
            threads,
        ),
        Command::Determinism {
            index,
            encoder_dir,
            code_dir,
            queries_npy,
            query_ids,
            output,
            query_tokens,
            k,
            rerank_k,
            cluster_top_t,
            ef_search,
            threads,
            repetitions,
        } => determinism(
            &index,
            &encoder_dir,
            &code_dir,
            &queries_npy,
            &query_ids,
            &output,
            query_tokens,
            SearchParamsV3 {
                k,
                rerank_k,
                cluster_top_t,
                ef_search,
            },
            threads,
            repetitions,
        ),
        Command::ClusterBenchmark {
            repair_policy,
            fine_centroids_npy,
            coarse_centroids_npy,
            fine_to_coarse_npy,
            code_dir,
            doclens_dir,
            cluster_ids,
            wave_sizes,
            threads,
            repetitions,
            progress_jsonl,
            output,
            dimension,
            max_doc_tokens,
        } => cluster_benchmark(
            &fine_centroids_npy,
            &coarse_centroids_npy,
            &fine_to_coarse_npy,
            &code_dir,
            &doclens_dir,
            repair_policy,
            cluster_ids,
            wave_sizes,
            threads,
            repetitions,
            &progress_jsonl,
            &output,
            dimension,
            max_doc_tokens,
        ),
    }
}
